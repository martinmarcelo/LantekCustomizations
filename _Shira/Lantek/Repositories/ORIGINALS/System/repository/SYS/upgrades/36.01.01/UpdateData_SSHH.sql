-- Update purchase backlog lines units with quantity units of line
UPDATE SSHH_PPOO_00000300
SET UCtName = SSHH_PPOO_00000200.QUANUCtName,
	UntName = SSHH_PPOO_00000200.QUANUntName
FROM SSHH_PPOO_00000300 INNER JOIN SSHH_PPOO_00000200 ON (
		SSHH_PPOO_00000300.POrdRef = SSHH_PPOO_00000200.OrdRef AND
		SSHH_PPOO_00000300.LineNumPO = SSHH_PPOO_00000200.LineNum )
WHERE SSHH_PPOO_00000300.UCtName <> SSHH_PPOO_00000200.QUANUCtName OR 
	  SSHH_PPOO_00000300.UntName <> SSHH_PPOO_00000200.QUANUntName