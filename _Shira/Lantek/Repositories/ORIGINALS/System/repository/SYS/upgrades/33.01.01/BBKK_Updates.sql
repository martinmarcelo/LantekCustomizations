--Initialize sales person field with the sale person of invoices
UPDATE BBKK_BBKK_00000200
SET BBKK_BBKK_00000200.SalesPerson = SSAA_IINN_00000100.EmpRef
FROM BBKK_BBKK_00000200 INNER JOIN SSAA_IINN_00000100
ON BBKK_BBKK_00000200.Invoice = SSAA_IINN_00000100.InvRef
AND BBKK_BBKK_00000200.AssocElement = 1


