-- corregir a rpm velocidades antiguamente expresadas en m/min
DECLARE @NuPi float
SET     @NuPi = 3.14159265359
UPDATE  DIS_CCTT_TTLL_00000100
SET     InSpeed = (DIS_CCTT_TTLL_00000100.InSpeed * 1000) / (@NuPi * DIS_CCTT_TTLL_00000100.DDiameter)
FROM    DIS_CCTT_TTLL_00000100 INNER JOIN
        DIS_PPTT_TTLL_00000100 AS T2 ON (DIS_CCTT_TTLL_00000100.DrillRef = T2.PunchRef AND T2.PType = 10 AND T2.PForm = 0)
WHERE   DIS_CCTT_TTLL_00000100.DDiameter > 0.0001 AND 
		  DIS_CCTT_TTLL_00000100.InSpeed > 0.0001
		
		
DELETE DIS_PPTT_TTLL_00000100
WHERE PType = 10


