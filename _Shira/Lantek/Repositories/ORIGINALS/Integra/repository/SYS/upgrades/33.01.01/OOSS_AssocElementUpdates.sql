-- Retrieve assoc element values
UPDATE OOSS_OOOO_00000200
SET OOSS_OOOO_00000200.RecordID = ISNULL((
										  SELECT TOP 1 SSAA_SSOO_00000100.RecID
										  FROM SSAA_SSOO_00000100, MMNN_MMOO_00000100
										  WHERE OOSS_OOOO_00000200.MnORef <> '' AND 
												MMNN_MMOO_00000100.OrdRef <> '' AND
												OOSS_OOOO_00000200.MnORef = MMNN_MMOO_00000100.MnOref AND
												MMNN_MMOO_00000100.OrdRef = SSAA_SSOO_00000100.OrdRef
										 ), 0),
	OOSS_OOOO_00000200.AssocElementType = 2,
	OOSS_OOOO_00000200.TblRef = 'SSAA_SSOO_00000100'
WHERE OOSS_OOOO_00000200.MnORef <> ''

UPDATE OOSS_OOOO_00000200
SET OOSS_OOOO_00000200.AssocElementType = 0, 
	OOSS_OOOO_00000200.TblRef = ''
WHERE OOSS_OOOO_00000200.RecordID = 0