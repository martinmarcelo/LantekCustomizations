-- @#LONGSCRIPT#@
-- Updates items cost method with their default warehouse inventory strategy cost method. If no default inventory is defined, cost method takes first warehouse's strategy. Otherwise cost method stays with its original value.

-- Common items
DECLARE @commonItemWarehouseManagement NVARCHAR
SET @commonItemWarehouseManagement = ISNULL((SELECT TOP(1) ParValue FROM SYST_CCPP_00000100 WHERE ParName = 'SYS_WHM_CommonItemManagement'), 0)
IF @commonItemWarehouseManagement = '1'
BEGIN
	UPDATE PPRR_PPRR_00000100
	SET PPRR_PPRR_00000100.CstMethod = ISNULL(ISNULL(
		(SELECT TOP 1 WWHH_IIVV_00000100.Strategy FROM WWHH_IIVV_00000100 WHERE ((WWHH_IIVV_00000100.PrdRef = PPRR_PPRR_00000100.PrdRef) AND (WWHH_IIVV_00000100.IsDefault = 1))) + 1,
		(SELECT TOP 1 WWHH_IIVV_00000100.Strategy FROM WWHH_IIVV_00000100 WHERE WWHH_IIVV_00000100.PrdRef = PPRR_PPRR_00000100.PrdRef) + 1), 
		PPRR_PPRR_00000100.CstMethod)
	WHERE ((PPRR_PPRR_00000100.DIS_PClass = 1) AND (PPRR_PPRR_00000100.Assembly = 0))
END

