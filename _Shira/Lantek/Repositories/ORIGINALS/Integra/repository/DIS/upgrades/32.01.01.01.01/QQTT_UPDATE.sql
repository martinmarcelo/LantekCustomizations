UPDATE QQTT_QQTT_00000200
SET DIS_WGHUCtName = CASE WHEN (DIS_IsWeightBased = 1) THEN UCtName
						  ELSE (SELECT TOP 1 UCtName FROM SYST_UUMM_00000800
								WHERE SYST_UUMM_00000800.TblRef = 'PPRR_PPRR_00000100' and SYST_UUMM_00000800.FldRef = 'Weight' and SYST_UUMM_00000800.USyName = 'MET')
				     END
